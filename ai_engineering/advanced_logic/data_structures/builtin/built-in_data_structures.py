# Built-in Data Structures in Python
# Python provides several built-in data structures that are commonly used in programming.

# 1. Lists
# Lists are ordered, mutable collections of elements.
my_list = [1, 2, 3, 4, 5]
print(my_list)

# 2. Tuples
# Tuples are ordered, immutable collections of elements.
my_tuple = (1, 2, 3, 4, 5)
print(my_tuple)

# 3. Sets
# Sets are unordered, mutable collections of unique elements.
my_set = {1, 2, 3, 4, 5}
print(my_set)

# 4. Dictionaries
# Dictionaries are unordered, mutable collections of key-value pairs.
my_dict = {'a': 1, 'b': 2, 'c': 3}
print(my_dict)